import { app } from 'electron'
import assert from 'node:assert/strict'
import { promises as fs } from 'node:fs'
import path from 'node:path'
import { store } from '../../src/main/store'
import { updateDocuments, deleteDocuments, deleteChats } from '../../src/main/batch'
import { loadAnnotations, saveAnnotations } from '../../src/main/annotationStore'
import { aliStore } from '../../src/main/ali/store'
import { aliMemory } from '../../src/main/ali/memory'
import { collectionPath } from '../../src/shared/collections'

app.setPath('userData', process.env.ARBOR_TEST_DIR!)
app.on('window-all-closed', () => {})
async function run() {
  await store.init()
  const a = await store.addWebLink({ url: 'https://example.com/a', title: 'A', author: '' })
  const b = await store.addWebLink({ url: 'https://example.com/b', title: 'B', author: '' })
  const c = await store.addWebLink({ url: 'https://example.com/c', title: 'C', author: '' })
  const first = await store.addCollection('Original')
  const second = await store.addCollection('Added')
  await store.updateDocument(a.id, { collections: [first.id], tags: ['original'] })
  await store.updateDocument(b.id, { tags: ['keep'] })
  assert.equal(await updateDocuments([a.id, b.id, a.id, 'missing'], {
    readingStatus: 'read', starred: true, collections: { mode: 'add', ids: [second.id] }, tags: { mode: 'add', values: ['new', ' new '] }
  }), 2)
  assert.deepEqual(a.collections, [first.id, second.id])
  assert.deepEqual(b.collections, [second.id])
  assert.deepEqual(a.tags, ['original', 'new'])
  assert.deepEqual(b.tags, ['keep', 'new'])
  assert.equal(a.readingStatus, 'read')
  assert.equal(b.starred, true)
  assert.equal(c.readingStatus, 'unread')
  await assert.rejects(() => updateDocuments([a.id], { readingStatus: 'reading', collections: { mode: 'add', ids: ['missing'] } }))
  assert.equal(a.readingStatus, 'read', 'Invalid batch must fail before changing any selected record')
  await updateDocuments([a.id, b.id], { collections: { mode: 'remove', ids: [second.id] }, tags: { mode: 'remove', values: ['new'] } })
  assert.deepEqual(a.collections, [first.id])
  assert.deepEqual(b.tags, ['keep'])
  await updateDocuments([a.id, b.id], { collections: { mode: 'replace', ids: [second.id] }, tags: { mode: 'replace', values: [] } })
  assert.deepEqual(a.collections, [second.id])
  assert.deepEqual(b.tags, [])
  console.log('PASS: bulk metadata edits preserve unselected documents and support add/remove/replace/clear without partial changes on invalid input')
  const chat = await store.createChat([a.id, b.id, c.id])
  const topic = await store.addResearchTopic({ name: 'Batch topic', docIds: [a.id, c.id] })
  await store.updateResearchTopic(topic.id, { chatId: chat.id })
  const excerpt = await store.addExcerpt({ docId: a.id, source: 'Preserved source', answer: 'Keep excerpt' })
  await store.setDocumentText(a.id, ['Extracted text'])
  await saveAnnotations(a.id, { version: 1, docId: a.id, notes: [], strokes: [], updatedAt: Date.now() })
  await loadAnnotations(a.id)
  assert.equal(await deleteDocuments([a.id, b.id, a.id, '../invalid']), 2)
  assert.ok(store.getDocument(c.id))
  assert.deepEqual(chat.docIds, [c.id])
  assert.deepEqual(topic.docIds, [c.id])
  assert.equal(excerpt.docMissing, true)
  await assert.rejects(() => fs.access(path.join(store.textsDir, `${a.id}.json`)))
  await assert.rejects(() => fs.access(path.join(store.root, 'annotations', `${a.id}.json`)))
  const otherChat = await store.createChat([c.id])
  await fs.mkdir(path.join(store.attachmentsDir, chat.id), { recursive: true })
  await fs.writeFile(path.join(store.attachmentsDir, chat.id, 'attachment.txt'), 'test')
  assert.equal(await deleteChats([chat.id, chat.id, '../invalid']), 1)
  assert.ok(store.getChat(otherChat.id))
  assert.equal(topic.chatId, undefined)
  await assert.rejects(() => fs.access(path.join(store.attachmentsDir, chat.id)))
  console.log('PASS: bulk deletion deduplicates IDs, preserves unselected records/excerpts, cleans references, text and conversation attachments')
  await aliStore.init()
  await aliMemory.init()
  const aliSessions = await Promise.all([aliStore.create(), aliStore.create(), aliStore.create()])
  const memoryBefore = await fs.readFile(aliMemory.memoryFile, 'utf8')
  await assert.rejects(() => aliStore.removeMany(null as unknown as string[]))
  assert.equal(await aliStore.removeMany([aliSessions[0].id, aliSessions[1].id, aliSessions[0].id, 'missing']), 2)
  await aliStore.reload()
  assert.deepEqual(aliStore.list().map(session => session.id), [aliSessions[2].id])
  assert.equal(await fs.readFile(aliMemory.memoryFile, 'utf8'), memoryBefore)
  console.log('PASS: Ali bulk deletion persists only selected removals, handles duplicate/missing IDs and preserves long-term memory')
  const root = await store.addCollection('Research', undefined, '#123abc')
  const child = await store.addCollection('Battery', root.id, '#456def')
  const grandchild = await store.addCollection('VAE', child.id)
  const importSource = path.join(app.getPath('userData'), 'folder-import.txt')
  await fs.writeFile(importSource, 'Folder import fixture')
  const imported = await store.addDocument(importSource, 'Imported into folder', child.id)
  assert.deepEqual(imported.collections, [child.id])
  const rootImport = await store.addDocument(importSource, 'Root import')
  assert.deepEqual(rootImport.collections, [])
  const filesBeforeInvalidImport = await fs.readdir(store.filesDir)
  await assert.rejects(() => store.addDocument(importSource, 'Missing folder', 'missing'))
  assert.deepEqual(await fs.readdir(store.filesDir), filesBeforeInvalidImport)
  console.log('PASS: local imports assign the chosen folder, root imports stay unfiled, missing folders create no files')
  assert.equal(collectionPath(store.data.collections, grandchild.id), 'Research / Battery / VAE')
  await assert.rejects(() => store.updateCollection(root.id, { parentId: grandchild.id, name: 'Must not change', color: '#ffffff' }))
  assert.equal(root.name, 'Research')
  assert.equal(root.color, '#123abc')
  assert.equal(root.parentId, undefined)
  await assert.rejects(() => store.updateCollection(child.id, { color: 'red;display:none' }))
  await assert.rejects(() => store.addCollection('   '))
  await store.updateDocument(c.id, { collections: [root.id, grandchild.id] })
  await store.updateCollection(child.id, { parentId: '', name: 'Moved', color: '#abcdef' })
  assert.equal(collectionPath(store.data.collections, grandchild.id), 'Moved / VAE')
  await store.deleteCollection(child.id)
  assert.equal(grandchild.parentId, undefined)
  assert.ok(store.getDocument(c.id))
  assert.ok(c.collections.includes(grandchild.id))
  await store.updateSettings({ uiFontSize: 20 })
  await assert.rejects(() => store.updateSettings({ uiFontSize: 99 }))
  assert.equal(store.data.settings.uiFontSize, 20)
  await store.init()
  assert.equal(store.data.settings.uiFontSize, 20)
  assert.equal(store.data.collections.find(item => item.id === root.id)?.color, '#123abc')
  await store.updateSettings({ uiFontSize: 14 })
  console.log('PASS: nested folders, move validation, persistent colors, safe folder deletion and interface font-size persistence')
}
app.whenReady().then(run).then(() => app.exit(0)).catch(error => { console.error(error); app.exit(1) })
